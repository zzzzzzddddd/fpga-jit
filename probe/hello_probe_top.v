`timescale 1ns/1ps
// ============================================================
// hello_probe_top.v — 零假设的最小工程
// ============================================================
// 【它是干什么的】
//   8 位数码管一起从 0 数到 F 再回 0，每位大约 0.3 秒跳一次，永久循环。
//
//   没有 SD 卡、没有状态机、没有 FAT32、没有我写的任何逻辑，
//   只有：时钟 -> 分频计数 -> 段码译码 -> 扫描输出。
//
// 【为什么需要它】
//   到现在为止，所有失败现象（"全 0"、"0······0"、"没有 9"）
//   都无法区分这三种成因：
//     (a) 工具链 / 下载 / 时钟 / 引脚  有问题
//     (b) 我的状态机  有问题
//     (c) SD 卡 / 卡座硬件  有问题
//   它们都表现为"数码管显示不对"，再加逻辑也还是在猜。
//
//   这个工程把 (b) 和 (c) 整个删掉。于是只有两种结果：
//
//     ★ 数码管在 0..F 循环  =  工具链、下载、时钟、引脚、扫描
//                              这一整条链路都是好的。
//                              (a) 排除。可以放心回去查 (b)/(c)。
//
//     ★ 数码管不动 / 全灭  =  问题在 (a)。跟 SD 卡、跟 FAT32、
//                              跟我的状态机都没有任何关系，
//                              别再往那个方向查。
//
//   一句话：这个工程过了，才有必要讨论别的；这个工程不过，
//   讨论别的都是浪费时间。
// ============================================================
module hello_probe_top (
    input  wire        clk,        // 50MHz 板时钟 R7
    input  wire        rst_n,      // 复位按键 A2（低有效）
    output wire [7:0]  seg_sel,    // 位选，低有效 one-hot
    output wire [7:0]  seg_data    // 段选，低有效，MSB 是小数点
);

// ------------------------------------------------------------------
// 上电复位：50MHz 下数 20ms
// ------------------------------------------------------------------
reg [19:0] por_cnt;
reg        por_rst_n;

always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
        por_cnt   <= 20'd0;
        por_rst_n <= 1'b0;
    end else if (por_cnt != 20'd1_000_000 - 20'd1) begin
        por_cnt   <= por_cnt + 20'd1;
        por_rst_n <= 1'b0;
    end else
        por_rst_n <= 1'b1;
end

// ------------------------------------------------------------------
// 主计数：每 0.3 秒加一。50MHz * 0.3 = 15_000_000
//   取 24 位（2^24 = 16.7M，够）
//   只取低 4 位显示 -> 0..F 循环
// ------------------------------------------------------------------
reg [23:0] tick_cnt;
reg [3:0]  digit;

always @(posedge clk or negedge rst_n) begin
    if (!rst_n || !por_rst_n) begin
        tick_cnt <= 24'd0;
        digit    <= 4'd0;
    end else if (tick_cnt >= 24'd15_000_000 - 24'd1) begin
        tick_cnt <= 24'd0;
        digit    <= digit + 4'd1;
    end else
        tick_cnt <= tick_cnt + 24'd1;
end

// ------------------------------------------------------------------
// 7 段译码（低有效：1=灭）。字形和 src/seg_decoder.v 一致。
// ------------------------------------------------------------------
function [6:0] seg7;
    input [3:0] d;
    begin
        case (d)
            4'h0: seg7 = 7'b100_0000;
            4'h1: seg7 = 7'b111_1001;
            4'h2: seg7 = 7'b010_0100;
            4'h3: seg7 = 7'b011_0000;
            4'h4: seg7 = 7'b001_1001;
            4'h5: seg7 = 7'b001_0010;
            4'h6: seg7 = 7'b000_0010;
            4'h7: seg7 = 7'b111_1000;
            4'h8: seg7 = 7'b000_0000;
            4'h9: seg7 = 7'b001_0000;
            4'ha: seg7 = 7'b000_1000;
            4'hb: seg7 = 7'b000_0011;
            4'hc: seg7 = 7'b100_0110;
            4'hd: seg7 = 7'b010_0001;
            4'he: seg7 = 7'b000_0110;
            default: seg7 = 7'b000_1110;   // 'F'（不是全灭 —— 0xF 要能看见）
        endcase
    end
endfunction

// 8 位显示同一个数字；DP 灭
wire [7:0] sd = {1'b1, seg7(digit)};

seg_scan u_seg_scan(
    .clk        (clk      ),
    .rst_n      (por_rst_n),
    .seg_sel    (seg_sel  ),
    .seg_data   (seg_data ),
    .seg_data_0 (sd),
    .seg_data_1 (sd),
    .seg_data_2 (sd),
    .seg_data_3 (sd),
    .seg_data_4 (sd),
    .seg_data_5 (sd),
    .seg_data_6 (sd),
    .seg_data_7 (sd)
);

endmodule
