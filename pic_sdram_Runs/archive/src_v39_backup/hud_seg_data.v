// ============================================================================
// hud_seg_data.v -- 8 位数码管的显示内容（video_clk 域）
//
// ============================================================================
// 【这一版是"上板诊断面板"，不是读数面板】
// ============================================================================
// 本工程【不跑仿真】，唯一的验证手段是"改完 -> TD 综合 -> 上板"。
// 所以数码管的用途从"再显示一遍屏幕上已有的读数"改成"显示屏幕上根本没有的
// 内部状态"—— 这是板子上唯一能看进 FPGA 内部的窗口。
//
// 显示分配（8 位，物理上左 -> 右）：
//
//   位号   D0        D1       D2        D3       D4        D5        D6        D7
//         ┌────────┬────────┬────────┬────────┬────────┬────────┬────────┬────────┐
//         │ 界面号 │SD状态码│ WAV    │ 音频   │ 样本   │ 峰值   │ 报警   │ 轮播位 │
//         │        │        │ 最深态 │ 健康位 │ 计数   │ 幅度   │ 标志   │        │
//         │        │        │(粘滞)  │        │(本次)  │(本次)  │        │        │
//         └───▲────┴───▲────┴───▲────┴───▲────┴───▲────┴────────┴───▲────┴───▲────┘
//             │        │                                          │        │
//             │        │            DP[0] = 报警指示灯 ──────────┘        │
//             └ 0..5    └ 见下                                        0/1
//
//   D0 disp_page  0=三表总览 1=压力放大 2=温度放大 3=液位放大 4=待机巡检 5=储气罐故障
//   D1           open 成功过之前 = fat32_reader 的码；成功过之后 = bmp_read 的码。
//                bmp_read: 1=空闲 2=找图中 3=读头 4=读像素 7=重试等待
//                          9=等 open_done 10=等翻译 11=等帧缓冲
//                fat32   : 1=空闲 2=等MBR 3=等BPB 4=等目录项 5=跟目录簇链
//                          6=open结束 7=跟簇链 8=等FAT项 9=翻译完成
//   D2           ★ 本次 play 以来 wav_state_code 达到过的最大值 0..7 ★（粘滞）
//                0=空闲 1=发open 2=等open 3=发翻译 4=发扇区读 5=收字节
//                6=等播放(★到过 6 就是它进过播放态、该出声了★) 7=出错
//                ★ 取"最大值"而不是直接显示 state_code ★
//                  一段 WAV 只有约 1 秒，播完 FSM 就回 A_IDLE（0）——
//                  直接显示的话，等眼睛挪到数码管上面早就读成 0 了，
//                  "播成功了"和"压根没播"分不开。
//                ★ 7 ⇒ 出过错；2 ⇒ 卡上根本没打开这个 WAV（文件名/目录项）；
//                  4/5 ⇒ open 好了、正在读，但从没进播放态 ★
//                （第十九版这里是 img_slots.done_cnt 预载张数 ——
//                  六槽预载那条链已经验完，让位给音频）
//   D3           {!wav_err, wav_fmt_ok, wav_rate_ok, aud_mute}
//                bit3 ★取反的 WAV 错误★（1 = 没出错；err 是粘滞的）
//                bit2 PCM+单声道+16bit 三项全对
//                bit1 采样率在 wav_loader 的支持表内
//                bit0 ★静音标志★（= SW4 的实际电平）
//                ⇒ ★健康值 'E'(1110)★；'D' = 只有静音位是 0；
//                  bit3=0 的（'0'..'7'）= WAV 出错（打开失败/头非法）
//   D4           ★★ 第二十四版：样本【速率】★★ = 每秒样本数 ÷ 4096，
//                取本次 play 以来见过的最大值（粘滞）。
//                **正常应读 '3'**（16000 ÷ 4096 = 3）
//                  3    ⇒ 约 16kHz，速率正常
//                  1    ⇒ 约 8kHz，只有一半
//                  0    ⇒ 一个样本都没进来（或稀疏到 < 4096/秒）
//                ★ 为什么把旧的"个数，饱和 14"换掉（务必记住）★
//                  旧口径下 **"每秒 16000 个"和"整段总共只来 14 个"
//                  在面板上读出来完全一样**，而 D5 只要整段被过一遍
//                  就会爬到正确峰值 —— 哪怕样本是极低速率涓流出来的。
//                  ⇒ "D4=E 且 D5 是正确峰值" 完全兼容 "样本稀疏到听不出语音"，
//                    第二十三版上板正是"三项全对却没声"，空洞就在这。
//                  判据从"有无"改成"计数"（同 fat32-migration-status 那条教训）。
//                ★ 钳到 14 而不是 15：4'hF 会被 blank_if_ff 吃成全灭 ★
//                  （6 位计数直接截成 4 位可能得 4'hF —— 那会把"速率爆表"
//                    显示成"什么都没有"，正好是最容易看反的方向）
//   D5           ★ 本次 play 以来见过的【最大 |样本|】的高 4 位 ★
//                ★ "数字侧到底有没有真音频数据"的唯一硬证据 ★
//                16 位有符号的 |x| ≤ 32768 ⇒ **D5 只可能是 0..8**。
//                  0    ⇒ 样本全是 0（没数据 / 读到一片零区）
//                  1..8 ⇒ 真有信号，数字就是 PCM 幅度量级
//                ★★ 应当是 7/5/5/2/2/6 ★★（各文件自己的 peak>>12）
//                  ★ 第二十七版：六段音量已归一（tools/wav_level_match.py），
//                    旧值是 4/4/3/7/7/6 且那时六值互不相同。**归一之后
//                    page1/2 都是 5、page3/4 都是 2 —— 有两对相邻页相同**
//                    ⇒ "翻页时 D5 不动就是病"这条【不再逐页成立】，
//                    别再拿它当翻页/取文件链路的判据；它现在只回答
//                    "这一段到底有没有真数据"（恒 0 = 没数据）。★
//                  离线复算：tools/wav_align_check.py。
//                  ★ 实测过"六页全 8"（第二十版）：8 只可能来自 0x8000
//                    这一个值，而六个 WAV 对齐正确时都不含它 ⇒ 那不是
//                    "打开同一个文件"，是**播放侧取字节错开了一位**
//                    （见 src/wav_loader.v [3/3]）。★
//                ★ 用【最大值】而不是瞬时值 ★
//                  瞬时样本在 16kHz 上一直在变，数码管根本读不了 ——
//                  本工程已经因为"用瞬时量做探针"踩过两次坑（见上面第十六
//                  版那段），不再踩第三次。
//                ★★ 量的位置是【静音之前】的 wav_pcm（wav_loader 直接吐的
//                   样本，不经过 audio_pwm 的 mute）★★
//                  于是"D4 非 0 且 D5 非 0 而 D3 的低位=1"唯一地指向
//                  ★数字侧全好、只是被 SW4 静音了★ —— 这正是要分开的那一种。
//
//   ★★ 第二十五版：音频【输出通路】从 H11 改成 HDMI 内嵌音频，
//      但上面 D2..D5 的口径和健康值【一个都没变】★★
//      原因：这四个量量的都是【audio_pwm / audio_mode 之前】的源
//      （wav_pcm / wav_pcm_stb / wav_state_code / wav_err / fmt_ok /
//        rate_ok / aud_mute），跟"这些样本最后从哪个口出去"无关。
//      ⇒ 判据照旧，不需要重新标定。
//
//      ★★ 它还顺带给出一条推理链（第二十五版新增，用来消除"没声"的歧义）★
//          D2 ≥ 6  ⇒ wav_loader 进过 A_WAITPLY ⇒ 本段确实出过样本
//                    ⇒ top.v 的粘滞标志 wav_active = 1（它就是拿
//                      "第一个真样本 wav_pcm_stb"置位的，同一件事的两面）
//          D3 = 'E' ⇒ 没出错 / 格式对 / 采样率对 / 【没被 SW4 静音】
//          两者同时成立 ⇒ audio_mode 当时【一定是 M_PCM】
//        ⇒ **面板全对却仍然没声，问题只可能在 HDMI 那一段
//          （I2S_receiver → HDMI 核 → TMDS → 显示器），不可能是模式选择、
//          也不可能是 CDC 之前的数据。** 这条链就是为了把"没声"钉死在一处。
//        ★ 反例，务必记住：**不能**直接拿 wav_loader 的 playing 做模式判据 ——
//          它每 16ms 回填半区时会掉 0 一次（详见 top.v 那段粘滞标志的注释），
//          那会让 audio_mode 周期性硬切、产生 62Hz 的断音/咔哒。
//
//   ★ D2 最大 7、D4 最大 14、D5 最大 8，都碰不到 4'hF ★
//     （见 seg_disp_top.v 的 blank_if_ff）
//   ★ 第十九版修过的一个探针病，仍然有效：wr_finish 在 125MHz 下只有一拍宽
//     (8ns)，而 sd_card_clk 是 100MHz(10ns) —— 直接拿两级触发器去采会
//     【整次丢失】。现在 top.v 先用翻转握手把它变成电平跳变再同步。★
//   D6/D7 ★ 第十二版：hud_overlay 的【入口 / 出口】A/B 计数 ★
//                D6 = 出口(hud_rgb，真正送进 HDMI 的那根线)亮像素个数高 4 位
//                D7 = 入口(vout_data_raw)同口径个数高 4 位
//                演进过程（每一步都是上板逼出来的）：
//                  写侧按位或 → 太弱；写侧 R>=32 有无 → 太弱；
//                  显示端 R>=32 有无 → **还是太弱**（一个亮像素就能点亮）；
//                  改成计数后上板：入口侧 D6=8 = 33792 = 整幅图都在，
//                  可屏幕依然全黑 ⇒ 说明问题在"叠加层之后"。
//                于是这一版把同一个计数探针一头一尾各接一个：
//                  D6=8 D7=8 -> 底图送进 HDMI 了 ⇒ 查 HDMI 核/PHY/显示器
//                  D6=0 D7=8 -> ★ hud_overlay 把底图吃掉了 ★
//                  D6=0 D7=0 -> 输入侧也空 ⇒ 回帧缓冲那条链查
//                标定：真图铺满整帧 = 11% × 307200 = 33792 = 0x8400 ⇒ 高 4 位 8
//                ★ 原来的 D6=报警标志 / D7=alarm_on 已让位给诊断，
//                  端口没删（alarm_on 还挂在 D0 的小数点上）。★
//
//   ★ D2..D5 是十六进制直显（seg_decoder 支持 0-9/A-F），二进制位要按上表拆。
//     例：D3 读作 'C' = 1100 = fbm_req=1,fbm_grant=1,bmp_req=0,bmp_grant=0
//   ★ 2026-10-03 之前 D2..D5 显示的是四个拨动开关电平，已废弃 ——
//     开关电平人眼直接看板子就有，而这四个信号在屏幕上一个都看不到。
//
// ---------------------------------------------------------------------------
// ★ 为什么第 0 步必须先看 D2..D5 ★
//   hud_switches.v 的 INVERT = 4'b0000 是【从来没有实测过】的猜测值。
//   四个开关现在全都有功能，极性猜反了演示会整片反过来 —— 而"功能没实现"
//   和"开关反了"在板子上看起来一模一样，极容易误判。
//   烧进去先逐个拨 SW1..4，看 D2..D5 是 0 还是 1，据此决定 INVERT。
//
// ★ 为什么不再显示 row1/row2 ★
//   屏幕上的三行读数是实时可见的，数码管再显示一遍是浪费唯一位宽有限的窗口；
//   而 disp_page / state_code / 开关电平 / 报警标志 在屏幕上【一个都看不到】。
//   09-30 那次"图片乱码 + 按键全失效"最后卡在"当时 state_code 是几"这个问题上
//   没法回答 —— 这次把它常显出来。
//
// 段的两个坑（下面代码里有对应处理）：
//   1. 段码和 DP 都是【低有效】。空白是 4'hF，DP 灭是 1'b1。
//   2. 数码管按下标递增是【从右往左】的，所以 dig[3:0] 是 D0（最左）。
//
// 跨时钟域：video_clk(25MHz) -> clk(50MHz)，用"数据先装、toggle 后翻"的握手。
// ============================================================================
module hud_seg_data(
    input  wire        clk,          // video_clk 25MHz
    input  wire        rst_n,
    input  wire        frame_tick,   // 每帧一个脉冲，做握手节拍
    input  wire [2:0]  disp_page,    // 当前界面 0..5
    input  wire [2:0]  rot_page,     // ★ 轮播/手动选择位 0..4（不含报警页）★
                                     //   和 disp_page 的区别：disp_page 会被
                                     //   报警强行拉去 5，rot_page 不会。
                                     //   所以"按 K2 时它动不动"才是 K2 好坏的判据。
    input  wire [3:0]  state_code,   // SD 卡状态码（video_clk 域，外面已同步）
    input  wire [3:0]  sw,           // 拨动开关实际电平（已同步消抖，诊断版已不显示）
    input  wire [23:0] diag,         // ★ 诊断总线（见下面 D2..D7 的说明）
    input  wire        fl_p, fl_t, fl_l,  // 三个量的报警标志
    input  wire        alarm_on,     // 报警界面有效
    // ---- 跨到 clk 域 ----
    output wire [31:0] seg_dig,      // 8 个 nibble，[3:0] = 最左一位
    output wire [7:0]  seg_dp,       // 8 个小数点，【低有效】
    output reg         seg_tog       // 数据有效 toggle
);

    // 数字 >= 10 时给 4'hF（空白），避免显示出奇怪的段型
    function [3:0] dec1;
        input [3:0] v;
        begin
            dec1 = (v <= 4'd9) ? v : 4'hF;
        end
    endfunction

    // 单个开关位 -> '0' / '1'
    function [3:0] bit1;
        input b;
        begin
            bit1 = b ? 4'h1 : 4'h0;
        end
    endfunction

    wire [3:0] d_page  = dec1({1'b0, disp_page});
    // ★ 2026-10-03 第十三版：D1 改成十六进制【直显】，不再过 dec1()。★
    //   dec1() 会把 >=10 映射成 4'hF，而 seg_disp_top.v:75 的 blank_if_ff()
    //   把 4'hF 变成【全灭】—— 于是 state_code = 10/11 (S_XL / S_READ_WAIT，
    //   恰恰是最需要看见的两个状态) 会显示成全灭，和"这位数码管坏了"分不开。
    //   state_code 最大 11，十六进制直显碰不到 4'hF。
    wire [3:0] d_state = state_code;

    // ================================================================
    // ★ 2026-10-03 第十三版：这一版专门查"六页工况页只能到两页" ★
    // ================================================================
    //   现象：板上按 K2 翻页，只能看到 0 和 5，中间 1..4 全不见。
    //   已查明三条互相纠缠的线索，必须【同时】看到才能分开：
    //
    //   (1) hud_data_gen 里 `dst_page = alarm_active ? 3'd5 : rot_page`
    //       —— 报警一有效，目标页恒为 5，怎么按 K2 都不动。
    //   (2) hud_data_gen 的脚本化监测量八段里有七段越限 ⇒ 报警几乎常驻；
    //       只有第 0 段 {press=95,temp=60,level=55} 是安全的，那一段里
    //       rot_page 才会露出来 —— 这正好解释"0 那一页偶尔出现"。
    //   (3) 所以要判 K2 到底有没有生效，就必须看【不受报警影响的 rot_page】。
    //
    //   D2..D5 = 四个拨动开关的实际电平（已同步消抖）
    //            -> 定 hud_switches.v 的 INVERT 极性。INVERT=4'b0000 是
    //               【从来没有实测过】的猜测值；SW2=确认报警(压制自动跳转)、
    //               SW3=强制报警页。极性反了 SW2 就永远确认不了 ⇒ 页面解锁不了。
    //   D6     = {fl_p, fl_t, fl_l, alarm_on} -> 到底是哪个量在报警
    //   D7     = rot_page 0..4 -> ★ 按 K2 时它动不动 = K2 是好是坏 ★
    //
    //   D6 的读法（十六进制，位3=fl_p 压力 / 位2=fl_t 温度 / 位1=fl_l 液位 / 位0=alarm_on）：
    //       '1' -> 只有 alarm_on，无越限（= SW3 强制报警页）
    //       '9' -> alarm_on + 压力越限        '5' -> alarm_on + 温度越限
    //       '3' -> alarm_on + 液位越限        '0' -> 根本没报警
    //   ★ D6 四位全 1 会显示成全灭（blank_if_ff），所以钳成 'E' ★
    // ================================================================
    // ★ 2026-10-04 第十六版：D2..D5 全部换成【粘滞 / 本次】的量 ★
    // ================================================================
    //   演进（每一版都是被上一次上板读数逼出来的）：
    //     第十三版：D2..D5 = 四个拨动开关的原始电平（那件事已查完，作废）
    //     第十四版：D2/D4 = 图号链 img_idx_sd / bmp_file_idx，读到 D2=D4=0
    //               而 D0 在变 —— 当时解释不了，其实那正是"页->图断在跨域"的
    //               样子，只是被别的噪声盖住了
    //     第十五版：D2 = fat32_bmp_state、D5 = 每秒读完成扇区数 —— 两个都有病：
    //               fat32_bmp_state 是【瞬时】的，停车后读到的只是停车后的值；
    //               D5 数的是整条 SD 总线，按 K2 触发的 WAV 播报也计入，
    //               "跳一下 7 再归 0"很可能就是音频读完了，跟底图无关
    //   ⇒ 这一版全部换成停车后仍然可读的量，一次按压就能定性：
    //
    //   D2 = bmp_file_idx  本次实际请求的文件号 0..5（粘滞，直到下次 open）

    //                      ★ 应恒等于 D0；不等 ⇒ 跨域那段断了，去查
    //                        img_idx_sd / page_chg_sd，不要查 SD ★
    //   D3 = dg_lvl        本次取图进度 0..5（每次取图清零重爬）
    //                      ★ 3=找到文件没进 S_READ；4=进了 S_READ 出不来；
    //                        5=读完整了 ⇒ 换图失败的话问题在视频侧 ★
    //   D4 = {wr_finish_seen, dg_end_seen, dg_last_err, 1'b0}
    //                      bit3=★整帧真的写进过 SDRAM★（wr_finish_raw 见过）
    //                      bit1=★最近一次读完是零有效字节★
    //                          =1 ⇒ 卡根本没回数据（超时兜底在救场）
    //   D5 = dg_wrfin_cnt  wr_finish_raw 累计次数 0..9（饱和不回绕）
    //                      ★ 0 = 本次上电从没把一整帧推进 SDRAM ★
    //   ★ 取值域：D2 0..5、D3 0..5、D4 见上、D5 0..9
    //     —— 都碰不到 4'hF，不会被 blank_if_ff 吃成全灭 ★
    //   ★★ 第十七版的关键对照：D3=5（读完了）而 D4 bit3=0 / D5=0（没落盘）
    //      ⇒ 问题在【写通路】；反过来若 D5 每按一次涨一格 ⇒ 写是好的，
    //        要回去查显示侧为什么不换缓冲 ★★
    // ================================================================
    // ★ 2026-10-04 第二十版：D2..D5 全部换成【音频链路】的量 ★
    // ================================================================
    //   图片那条链（六槽预载）已经上板验完，面板让位给音频。
    //   起因：用户报"只有电流声、没有文字播报"，而音频路径在板上
    //   【完全没有可见性】—— 见文件头 D2..D5 的新说明。
    //   这四个量的设计原则和第十六版一致：**只用本次/粘滞量**；
    //   D5 还特意用【最大值】而不是瞬时值（瞬时样本 16kHz 一直在变）。
    //   ★ 判读顺序（翻一次页，然后慢慢看数码管就够 —— 全是粘滞量）：
    //       D3='E' D2=6 D4=3 D5>0 ⇒ 数字侧一切正常 ⇒ 第二十五版起音频走 HDMI，
    //                               所以接着去查 HDMI 那一段（I2S_receiver →
    //                               HDMI 核 → TMDS → 显示器），
    //                               而不是 PWM 之后的模拟段
    //       D3='D'                ⇒ 是【静音】那一位 ⇒ SW4 在静音侧
    //                               （此时 D4/D5 仍然非 0，因为量的位置在
    //                                 mute 之前 —— 这条最省事，先看它）
    //       ★ D2=6 而 D4=1 或 0   ⇒ ★速率不够★ 进了播放态但样本稀疏
    //                               ⇒ 查 FSM 为什么离开 A_WAITPLY
    //                                 （strobe_cnt 被清零 ⇒ sample_tick 稀疏）
    //                               ★ 这正是第二十四版新加的那一档 ——
    //                                 第二十三版就是"D4=E/D5 对却没声"，
    //                                 旧口径读不出这一档。★
    //       D2=6 而 D5=0          ⇒ 样本流着但全是 0 ⇒ 卡上这个 WAV 是空数据
    //       D2 停在 2/4/5 不动    ⇒ 从没进播放态（2=没打开文件）⇒ 查目录项
    //       D2=7                  ⇒ wav_err 置位（打开失败/头非法）
    // ================================================================
    wire [3:0] d_d2 = diag[3:0];     // wav_st_max 本次到达过的最大状态 0..7
    wire [3:0] d_d3 = diag[7:4];     // {!wav_err, fmt_ok, rate_ok, aud_mute} 健康'E'
    wire [3:0] d_d4 = diag[11:8];    // ★第二十四版★ 每秒样本数÷4096（粘滞最大），正常读 3
    wire [3:0] d_d5 = diag[15:12];   // 本次 play 以来最大 |样本| 高 4 位
    wire [3:0] d_d6_raw = {fl_p, fl_t, fl_l, alarm_on};
    wire [3:0] d_d6 = (d_d6_raw == 4'hF) ? 4'hE : d_d6_raw;
    wire [3:0] d_d7 = dec1({1'b0, rot_page});   // rot_page 0..4，碰不到 4'hF

    // dig[3:0]=D0(最左) ... dig[31:28]=D7(最右)
    wire [31:0] dig_nxt = {d_d7, d_d6, d_d5, d_d4, d_d3, d_d2,
                           d_state, d_page};

    // 小数点（低有效，0 = 点亮）：只留 D0 上的报警指示灯，其余常灭
    wire [39:0] pay_nxt = {
        1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1, 1'b1,
        ~alarm_on,     // [32] -> seg_dp[0]，挂在 D0 上
        dig_nxt        // [31:0] -> seg_dig
    };

    // ==================================================================
    // 跨时钟域发送端
    //
    // 顺序有讲究：第 n 拍先把数据锁进 pay_v，第 n+1 拍才翻 seg_tog。
    // 如果同一拍做完（pay_v <= pay_nxt; seg_tog <= ~seg_tog;），接收域的
    // 同步器有可能刚好在数据还没稳定时采到新 toggle，锁进去的是
    // "新 toggle + 旧数据" —— 数码管会慢一帧，那一帧和屏幕状态对不上。
    // ==================================================================
    reg [39:0] pay_v;
    reg        tog_go;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            pay_v   <= 40'hFF_FFFF_FFFF;   // 全空白 / DP 全灭
            seg_tog <= 1'b0;
            tog_go  <= 1'b0;
        end else begin
            tog_go <= frame_tick;                 // 延迟一拍
            if (frame_tick) pay_v   <= pay_nxt;   // 第 n 拍：装数据
            if (tog_go)     seg_tog <= ~seg_tog;  // 第 n+1 拍：翻 toggle
        end
    end

    assign seg_dig = pay_v[31:0];
    assign seg_dp  = pay_v[39:32];

endmodule
